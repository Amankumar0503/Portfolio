export default function SocialIcon({
  name,
  className = "h-5 w-5",
}: {
  name: string;
  className?: string;
}) {
  const key = name.trim().toLowerCase();
  const Icon = icons[key];

  if (!Icon) {
    return <span className="text-2xl leading-none">{name}</span>;
  }

  return <Icon className={className} />;
}

